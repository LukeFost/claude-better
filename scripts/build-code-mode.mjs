#!/usr/bin/env node
// Builds code-mode/, the plugin `better-code-mode`, from the full plugin's sources.
//
// Claude Code's Code Mode refuses to start while an enabled plugin hooks tool calls
// (tool.call, tool.check, tool.judge, tool.run). `better` hooks three. This script
// writes a copy of the module without them, so the two plugins never drift apart:
//
//   // full-only:start ... // full-only:end   lines dropped from the copy
//   // code-mode: <code>                       line the copy uses in their place
//
// node scripts/build-code-mode.mjs          writes code-mode/
// node scripts/build-code-mode.mjs --check  exits 1 if code-mode/ is out of date

import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const NAME = 'better-code-mode'
const HEADER = '// Generated by scripts/build-code-mode.mjs. Edit the file it names, then run the script again.\n'
/** Event names that make Code Mode refuse a plugin (Claude Code 2.1.326), however the hook is spelled. */
export const REFUSED_HOOKS = /['"`](tool\.(call|check|judge|run)|agent\.(offer|spawn)|session\.send|classic\.\w+)['"`]/

const START = /^\s*\/\/ full-only:start\s*$/
const END = /^\s*\/\/ full-only:end\s*$/
const ALT = /^(\s*)\/\/ code-mode: (.*)$/

export function strip(source) {
  const out = []
  let dropping = false
  for (const [i, line] of source.split('\n').entries()) {
    if (START.test(line)) {
      if (dropping) throw new Error(`line ${i + 1}: full-only:start inside a full-only region`)
      dropping = true
    } else if (END.test(line)) {
      if (!dropping) throw new Error(`line ${i + 1}: full-only:end with no start`)
      dropping = false
    } else if (!dropping) {
      const alt = ALT.exec(line)
      out.push(alt ? `${alt[1]}${alt[2]}` : line)
    }
  }
  if (dropping) throw new Error('a full-only region is never closed')
  return out.join('\n')
}

/** Drops names the copy no longer uses from `import { ... } from './better'` lists. */
export function pruneImports(source) {
  return source.replace(/import (type )?\{([^}]*)\} from '(\.\/better|\.\.\/types)'/g, (whole, type, names, from) => {
    const rest = source.replace(whole, '')
    const kept = names.split(',').map((n) => n.trim()).filter((n) => n && new RegExp(`\\b${n}\\b`).test(rest))
    if (!kept.length) return ''
    const body = names.includes('\n') ? `\n  ${kept.join(', ')},\n` : ` ${kept.join(', ')} `
    return `import ${type ?? ''}{${body}} from '${from}'`
  }).replace(/\n{3,}/g, '\n\n')
}

const read = (p) => readFileSync(join(root, p), 'utf8')

export function build() {
  const manifest = JSON.parse(read('.claude-plugin/plugin.json'))
  const register = pruneImports(strip(read('hooks/register.tsx'))).replaceAll("plugin: 'better'", `plugin: '${NAME}'`)
  if (REFUSED_HOOKS.test(register)) throw new Error(`the copy still has a hook Code Mode refuses: ${REFUSED_HOOKS.exec(register)[0]}`)
  if (/\$\.(tool\.register|agent\.spawn)\b/.test(register)) throw new Error('the copy still registers a tool or spawns an agent')
  const types = read('types/index.d.ts').replace(/^(\s*)better: \{$/m, `$1'${NAME}': {`)
  if (!types.includes(`'${NAME}': {`)) throw new Error('types/index.d.ts: no `better: {` state block to rename')
  return {
    'code-mode/.claude-plugin/plugin.json': `${JSON.stringify({
      ...manifest,
      name: NAME,
      description: 'better for Code Mode: /better deepens a prompt with a read-only helper and puts it in your input box. It hooks no tool calls, so Claude Code\'s Code Mode starts with it enabled. Use it in place of `better`, not beside it.',
    }, null, 2)}\n`,
    'code-mode/hooks/hooks.json': '{ "modules": ["./register.tsx"] }\n',
    'code-mode/hooks/register.tsx': `${HEADER.replace('the file it names', 'hooks/register.tsx')}${register}`,
    'code-mode/hooks/better.ts': `${HEADER.replace('the file it names', 'hooks/better.ts')}${read('hooks/better.ts')}`,
    'code-mode/types/index.d.ts': `${HEADER.replace('the file it names', 'types/index.d.ts')}${types}`,
    'code-mode/guard/hooks/better.ts': `${HEADER.replace('the file it names', 'hooks/better.ts')}${read('hooks/better.ts')}`,
  }
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const files = build()
  const stale = []
  for (const [path, text] of Object.entries(files)) {
    const full = join(root, path)
    let now
    try {
      now = readFileSync(full, 'utf8')
    } catch {}
    if (now === text) continue
    stale.push(path)
    if (!process.argv.includes('--check')) {
      mkdirSync(dirname(full), { recursive: true })
      writeFileSync(full, text)
    }
  }
  if (process.argv.includes('--check') && stale.length) {
    console.error(`code-mode/ is out of date: ${stale.join(', ')}\nRun: node scripts/build-code-mode.mjs`)
    process.exit(1)
  }
  console.log(stale.length ? `wrote ${stale.join(', ')}` : 'code-mode/ is up to date')
}
